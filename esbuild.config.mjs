import * as esbuild from 'esbuild';
import { readFile } from 'node:fs/promises';

const dependencyNotices = await readFile(
  new URL('./THIRD_PARTY_NOTICES.txt', import.meta.url),
  'utf8',
);

const production = process.argv.includes('production');
const context = await esbuild.context({
  entryPoints: { main: 'src/main.ts', styles: 'src/styles.css' },
  outdir: '.',
  bundle: true,
  external: ['obsidian'],
  format: 'cjs',
  target: 'es2020',
  platform: 'browser',
  treeShaking: true,
  minify: production,
  sourcemap: production ? false : 'inline',
  define: { 'process.env.NODE_ENV': JSON.stringify(production ? 'production' : 'development') },
  banner: {
    js: `/* Thought Craft — generated by esbuild; edit src/ instead. */\n/*! ${dependencyNotices} */`,
    css: `/* Thought Craft — generated by esbuild; edit src/styles.css instead. */\n/*! ${dependencyNotices} */`,
  },
  logLevel: 'info',
});
if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
}
